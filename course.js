// --- HELPER FUNCTIONS & DRIVE LINK EXTRACTOR ---
function extractDriveFileId(inputUrl) {
    if (!inputUrl) return "";
    if (!inputUrl.includes('/') && !inputUrl.includes('.')) {
        return inputUrl;
    }
    const match = inputUrl.match(/\/file\/d\/([a-zA-Z0-9_-]+)/) || inputUrl.match(/[?&]id=([a-zA-Z0-9_-]+)/);
    return match ? match[1] : inputUrl;
}

function playLesson(driveUrl, title) {
    const iframe = document.getElementById('secure-video-player');
    const titleEl = document.getElementById('active-lesson-title');
    
    if (iframe && titleEl) {
        const fileId = extractDriveFileId(driveUrl);
        iframe.src = `https://drive.google.com/file/d/${fileId}/preview`;
        titleEl.textContent = title;
    }
}

function toggleWeek(index) {
    const list = document.getElementById(`lessons-week-${index}`);
    const icon = document.getElementById(`icon-week-${index}`);
    if (list) {
        if (list.style.display === 'none') {
            list.style.display = 'flex';
            icon.style.transform = 'rotate(180deg)';
        } else {
            list.style.display = 'none';
            icon.style.transform = 'rotate(0deg)';
        }
    }
}